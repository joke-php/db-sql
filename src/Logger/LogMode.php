<?php

declare(strict_types=1);

namespace Vasoft\Joke\Db\Sql\Logger;

/**
 * Режим логирования SQL-запросов.
 *
 * Определяет, какие этапы выполнения запроса должны фиксироваться в логе.
 */
enum LogMode: string
{
    /**
     * Логировать только выполнение запроса на стороне сервера.
     *
     * Фиксирует время отправки запроса и получения ответа от СУБД.
     * Не включает время передачи данных по сети и их обработки в PHP.
     * Подходит для оценки нагрузки на базу данных.
     */
    case ExecutionOnly = 'execution_only';

    /**
     * Логировать только чтение результатов (выборку строк).
     *
     * Фиксирует время, затраченное на извлечение данных из курсора
     * и их преобразование в массивы PHP. Включает время сетевой передачи.
     * Полезно для анализа производительности работы с большими объемами данных.
     */
    case FetchOnly = 'fetch_only';

    /**
     * Логировать все этапы: и выполнение, и чтение.
     *
     * Создает две записи в логе для одного SELECT-запроса:
     * 1. Сразу после выполнения (время ответа БД).
     * 2. После полного чтения результата (время выборки данных).
     * Рекомендуется использовать только при глубокой отладке.
     */
    case All = 'all';
}
